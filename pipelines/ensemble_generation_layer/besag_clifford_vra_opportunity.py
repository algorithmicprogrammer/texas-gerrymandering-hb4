def _spoke_worker(args):
    """
    Worker for a single spoke.
    args = (spoke_index, hub_assignment, seed)
    Returns (row_dict, assignment_dict) where row_dict is the score row
    and assignment_dict maps node_id -> 0-indexed district label.
    """
    spoke_idx, hub_assignment, seed = args
    endpoint_assignment = _run_chain_get_endpoint(hub_assignment, L_SPOKE, seed)
    my_updaters         = _build_updaters()
    endpoint_partition  = GeographicPartition(graph=graph,
                                              assignment=endpoint_assignment,
                                              updaters=my_updaters)
    scores = _functional_score_from_partition(endpoint_partition)

    # GeoSim revision: locality diagnostics. `frac_moved_vs_hub` and
    # `frac_moved_vs_enacted` are the fraction of precincts whose district
    # label differs between this spoke and the hub / the enacted plan. They
    # quantify how far L_SPOKE steps actually carry a plan, which is what the
    # chain length k controls (power, not validity). cut_edges and
    # county_splits are recorded so constraint tightening can be examined
    # post hoc and so the compactness of the simulated ensemble can be
    # compared to the enacted plan.
    n_prec = len(endpoint_assignment)
    moved_hub = sum(1 for n in endpoint_assignment
                    if endpoint_assignment[n] != hub_assignment[n])
    moved_enacted = (
        sum(1 for n in endpoint_assignment
            if endpoint_assignment[n] != ENACTED_ASSIGNMENT[n]) / n_prec
        if ENACTED_ASSIGNMENT else float('nan')
    )
    diagnostics = {
        'frac_moved_vs_hub': moved_hub / n_prec,
        'frac_moved_vs_enacted': moved_enacted,
        'cut_edges': len(endpoint_partition["cut_edges"]),
        'county_splits': endpoint_partition["county_splits"]["count"],
        'seed': seed,
    }
    return {'spoke': spoke_idx, **scores, **diagnostics}, endpoint_assignment


def run_spokes(hub_assignment):
    """
    Spawn M_SPOKES independent chains from hub, each of length L_SPOKE.
    Returns (DataFrame of scores, dict mapping spoke_idx -> assignment dict).
    """
    print(f"\n=== Running {M_SPOKES} spokes "
          f"(L={L_SPOKE} steps each, {N_WORKERS} workers) ===")
    t0    = time.time()
    seeds = [stdlib_random.randint(0, 10**9) for _ in range(M_SPOKES)]
    args  = [(i, hub_assignment, seeds[i]) for i in range(M_SPOKES)]
    rows  = []
    spoke_assignments = {}

    if N_WORKERS > 1:
        with mp.Pool(processes=N_WORKERS) as pool:
            for i, (row, assignment) in enumerate(
                    pool.imap_unordered(_spoke_worker, args)):
                rows.append(row)
                spoke_assignments[row['spoke']] = assignment
                if (i + 1) % 10 == 0:
                    print(f"  {i+1}/{M_SPOKES} spokes done "
                          f"({time.time()-t0:.0f}s elapsed)")
    else:
        for i, arg in enumerate(args):
            row, assignment = _spoke_worker(arg)
            rows.append(row)
            spoke_assignments[row['spoke']] = assignment
            if (i + 1) % 10 == 0:
                print(f"  {i+1}/{M_SPOKES} spokes done "
                      f"({time.time()-t0:.0f}s elapsed)")

    print(f"  All spokes complete in {time.time()-t0:.1f}s.")
    return pd.DataFrame(rows), spoke_assignments


