def compute_opportunity_scores(prob_dict,
                               m_bar_B, m_bar_L, m_bar_combined,
                               K=NUM_DISTRICTS):
    """
    Compute both the canonical opportunity functional O(pi) and
    its diversity-calibrated version F(pi).

    Canonical functional, justified by the axioms in the paper:
        O_g(pi) = sum_d p_d^g(pi)

    Diversity-calibrated gap:
        F_g(pi) = O_g(pi) - K * m_bar_g

    Coalition version:
        O_joint(pi) = sum_d max(p_d^B(pi), p_d^L(pi))
        F_joint(pi) = O_joint(pi) - K * m_bar_combined
    """
    if "N/A" in prob_dict.values():
        return {
            'O_B': float('nan'), 'O_L': float('nan'), 'O_joint': float('nan'),
            'F_B': float('nan'), 'F_L': float('nan'), 'F_joint': float('nan'),
            'baseline_B': K * m_bar_B,
            'baseline_L': K * m_bar_L,
            'baseline_joint': K * m_bar_combined,
        }

    p_B_list, p_L_list = [], []
    for d in sorted(prob_dict.keys()):
        hisp_prob, black_prob, neither_prob, combined_prob = prob_dict[d]
        p_L_list.append(hisp_prob)
        p_B_list.append(black_prob)

    p_B_arr = np.array(p_B_list, dtype=float)
    p_L_arr = np.array(p_L_list, dtype=float)

    O_B = float(p_B_arr.sum())
    O_L = float(p_L_arr.sum())
    O_joint = float(np.maximum(p_B_arr, p_L_arr).sum())

    baseline_B = float(K * m_bar_B)
    baseline_L = float(K * m_bar_L)
    baseline_joint = float(K * m_bar_combined)

    return {
        'O_B': O_B,
        'O_L': O_L,
        'O_joint': O_joint,
        'F_B': O_B - baseline_B,
        'F_L': O_L - baseline_L,
        'F_joint': O_joint - baseline_joint,
        'baseline_B': baseline_B,
        'baseline_L': baseline_L,
        'baseline_joint': baseline_joint,
    }


# Backwards-compatible alias. Existing calls will still work, but the new
# implementation should use compute_opportunity_scores() so O(pi) is retained.
def compute_opportunity_functional(prob_dict,
                                   m_bar_B, m_bar_L, m_bar_combined,
                                   K=NUM_DISTRICTS):
    scores = compute_opportunity_scores(
        prob_dict, m_bar_B, m_bar_L, m_bar_combined, K
    )
    return scores['F_B'], scores['F_L'], scores['F_joint']


def _functional_score_from_partition(partition):
    """
    Extract O_B, O_L, O_joint and F_B, F_L, F_joint from a partition.

    O(pi) is the axiom-derived theoretical functional.
    F(pi) is the diversity-calibrated score used for the primary
    lower-tail Besag-Clifford test.
    """
    final_state_prob, final_equal_prob, final_dist_prob = \
        partition["final_elec_model"]

    prob_dict = (final_state_prob if MODEL_MODE == 'statewide' else
                 final_equal_prob if MODEL_MODE == 'equal'     else
                 final_dist_prob)

    scores = compute_opportunity_scores(
        prob_dict, M_BAR_B, M_BAR_L, M_BAR_COMBINED
    )

    if "N/A" not in prob_dict.values():
        hisp_eff  = sum(1 for v in prob_dict.values()
                        if v[0] >= EFFECTIVENESS_CUTOFF)
        black_eff = sum(1 for v in prob_dict.values()
                        if v[1] >= EFFECTIVENESS_CUTOFF)
        distinct  = len(
            set(d for d, v in prob_dict.items() if v[0] >= EFFECTIVENESS_CUTOFF) |
            set(d for d, v in prob_dict.items() if v[1] >= EFFECTIVENESS_CUTOFF)
        )
    else:
        hisp_eff = black_eff = distinct = float('nan')

    return {
        **scores,
        'hisp_eff': hisp_eff,
        'black_eff': black_eff,
        'distinct_eff': distinct,
    }

