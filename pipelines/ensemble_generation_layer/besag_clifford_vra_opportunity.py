    m_bar_L        = hisp_cvap     / total_cvap
    m_bar_combined = combined_cvap  / total_cvap

    print(f"\nStatewide CVAP fractions:")
    print(f"  m_bar_B        = {m_bar_B:.4f}  ({100*m_bar_B:.2f}%)")
    print(f"  m_bar_L        = {m_bar_L:.4f}  ({100*m_bar_L:.2f}%)")
