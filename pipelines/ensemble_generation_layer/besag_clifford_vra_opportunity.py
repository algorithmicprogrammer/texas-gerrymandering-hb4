def save_distribution_plots(enacted_scores, spoke_df, run_name):
    """
    Save two figures:
      1. Canonical O(pi) null distributions.
      2. Calibrated F(pi) null distributions.

    The F(pi) figure is the primary testing figure.
    """
    def _plot(title, base_suffix, formulas):
        fig, axes = plt.subplots(1, 3, figsize=(15, 5))
        fig.suptitle(title, fontsize=12, fontweight='bold')

        for ax, (col, label, formula) in zip(axes, formulas):
            vals = spoke_df[col].dropna()
            enacted_val = enacted_scores[col]

            ax.hist(vals, bins=30, alpha=0.65,
                    edgecolor='white', linewidth=0.5,
                    label='Spoke null distribution')
            ax.axvline(enacted_val, linewidth=2.0, linestyle='-',
                       label=f'Enacted ({enacted_val:+.3f})')

            if col.startswith('F_'):
                ax.axvline(0, color='black', linewidth=1.2, linestyle='--',
                           label='Demographic baseline (F=0)')

            n_leq = (vals <= enacted_val).sum()
            p_val = (n_leq + 1) / (len(vals) + 1)
            ax.text(0.03, 0.97, f'p = {p_val:.4f}',
                    transform=ax.transAxes, va='top', ha='left',
                    fontsize=10, fontweight='bold')

            ax.set_xlabel('Score value (districts)', fontsize=10)
            ax.set_ylabel('Count' if ax is axes[0] else '', fontsize=10)
            ax.set_title(f'{label}\n{formula}', fontsize=9)
            ax.legend(fontsize=7, loc='upper right')
            ax.spines['top'].set_visible(False)
            ax.spines['right'].set_visible(False)

        plt.tight_layout()
        base = DIR + f'outputs/{base_suffix}_{run_name}'
        plt.savefig(base + '.pdf', bbox_inches='tight', dpi=300)
        plt.savefig(base + '.png', bbox_inches='tight', dpi=150)
        plt.close()
        print(f"Distribution plots saved:")
        print(f"  {base}.pdf")
        print(f"  {base}.png")
        return base + '.pdf'

    o_pdf = _plot(
        'Besag-Clifford Null Distribution -- Canonical Opportunity Scores O(pi)',
        'bc_canonical_O_distributions',
        [
            ('O_B',     'Black',     r'$O_B(\pi)=\sum_d p_d^B$'),
            ('O_L',     'Latino',    r'$O_L(\pi)=\sum_d p_d^L$'),
            ('O_joint', 'Coalition', r'$O_{\rm joint}(\pi)=\sum_d \max(p_d^B,p_d^L)$'),
        ]
    )

    f_pdf = _plot(
        'Besag-Clifford Null Distribution -- Calibrated Opportunity Gaps F(pi)',
        'bc_calibrated_F_distributions',
        [
            ('F_B',     'Black',     r'$F_B(\pi)=O_B(\pi)-K\bar{m}_B$'),
            ('F_L',     'Latino',    r'$F_L(\pi)=O_L(\pi)-K\bar{m}_L$'),
            ('F_joint', 'Coalition', r'$F_{\rm joint}(\pi)=O_{\rm joint}(\pi)-K\bar{m}_{\rm comb}$'),
        ]
    )

    return o_pdf, f_pdf


