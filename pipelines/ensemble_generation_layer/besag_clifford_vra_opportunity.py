# -*- coding: utf-8 -*-
"""
besag_clifford_vra_opportunity.py
==========================================

Axiom-Derived Minority Opportunity Functional
with Diversity Calibration and Besag-Clifford exact inference.

Conceptual structure
--------------------
This implementation separates the theoretical functional from the
calibration layer:

1. Canonical opportunity functional:

       O_g(pi) = sum_d p_d^g(pi)

   where p_d^g(pi) is the model-based probability that group g's
   preferred candidate wins district d under plan pi.

   This is the object justified by the axioms in the paper: anonymity,
   district additivity, monotonicity, and normalization. O_g(pi) is the
   expected number of opportunity districts.

2. Diversity-calibrated opportunity gap:

       F_g(pi) = O_g(pi) - K * m_bar_g

   where m_bar_g is the statewide CVAP share of group g. F_g(pi) is not
   a replacement for O_g(pi); it is a centered version of the canonical
   opportunity score.

3. Ensemble-standardized score:

       Z_g(pi_enacted) = (O_g(pi_enacted) - E_rho[O_g(pi)]) / sd_rho(O_g(pi))

   This calibrates the enacted plan to the state-specific opportunity
   frontier generated by the neutral ReCom ensemble.

4. Besag-Clifford exact lower-tail p-value:

       p = (# spokes with statistic <= enacted statistic + 1) / (M + 1)

   The primary test statistic is F_g, but O_g and Z_g are reported.
"""

