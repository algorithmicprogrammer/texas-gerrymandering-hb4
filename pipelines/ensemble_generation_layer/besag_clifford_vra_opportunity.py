# ============================================================


def _spoke_worker(args):
    """
    Worker for a single spoke.
    args = (spoke_index, hub_assignment, seed)
    Returns one row containing O, F, and legacy threshold scores.
    """
    spoke_idx, hub_assignment, seed = args
    endpoint_assignment = _run_chain_get_endpoint(hub_assignment, L_SPOKE, seed)
    my_updaters         = _build_updaters()
    endpoint_partition  = GeographicPartition(graph=graph,
                                              assignment=endpoint_assignment,
                                              updaters=my_updaters)
    scores = _functional_score_from_partition(endpoint_partition)
    return {'spoke': spoke_idx, **scores}


def run_spokes(hub_assignment):
    """
    Spawn M_SPOKES independent chains from hub, each of length L_SPOKE.
    Returns DataFrame with one row per spoke.
    """
    print(f"\n=== Running {M_SPOKES} spokes "
          f"(L={L_SPOKE} steps each, {N_WORKERS} workers) ===")
    t0    = time.time()
    seeds = [stdlib_random.randint(0, 10**9) for _ in range(M_SPOKES)]
    args  = [(i, hub_assignment, seeds[i]) for i in range(M_SPOKES)]
    rows  = []

    if N_WORKERS > 1:
        with mp.Pool(processes=N_WORKERS) as pool:
            for i, row in enumerate(pool.imap_unordered(_spoke_worker, args)):
                rows.append(row)
                if (i + 1) % 10 == 0:
                    print(f"  {i+1}/{M_SPOKES} spokes done "
                          f"({time.time()-t0:.0f}s elapsed)")
    else:
        for i, arg in enumerate(args):
            rows.append(_spoke_worker(arg))
            if (i + 1) % 10 == 0:
                print(f"  {i+1}/{M_SPOKES} spokes done "
                      f"({time.time()-t0:.0f}s elapsed)")

    print(f"  All spokes complete in {time.time()-t0:.1f}s.")
    return pd.DataFrame(rows)


# ============================================================
# STEP 4 — Exact Besag-Clifford p-values
# ============================================================



def compute_bc_pvalues(enacted_scores, spoke_df):
    """
    Rank enacted map among spoke endpoints.

    Primary lower-tail tests use F_B, F_L, and F_joint because these
    are demographically centered versions of the axiom-derived O scores.

    O_B, O_L, and O_joint are also reported, along with ensemble-standardized
    Z scores:
        Z = (O_enacted - mean(O_spokes)) / sd(O_spokes)
    """
    M = len(spoke_df)

    def _pval(enacted_val, col):
        vals   = spoke_df[col].dropna()
        n_leq  = (vals <= enacted_val).sum()
        n_geq  = (vals >= enacted_val).sum()
        p_low  = (n_leq + 1) / (len(vals) + 1)
        p_high = (n_geq + 1) / (len(vals) + 1)
        rank   = int(n_leq) + 1
        return p_low, p_high, rank

    def _z(enacted_val, col):
        sd = spoke_df[col].std()
        if pd.isna(sd) or sd == 0:
            return float('nan')
        return float((enacted_val - spoke_df[col].mean()) / sd)

    results = {
        'mode': MODEL_MODE, 'L_hub': L_HUB, 'L_spoke': L_SPOKE,
        'M_spokes': M, 'cutoff': EFFECTIVENESS_CUTOFF,
        'm_bar_B': M_BAR_B, 'm_bar_L': M_BAR_L,
        'm_bar_combined': M_BAR_COMBINED,
        'prop_seats_B':    NUM_DISTRICTS * M_BAR_B,
        'prop_seats_L':    NUM_DISTRICTS * M_BAR_L,
        'prop_seats_comb': NUM_DISTRICTS * M_BAR_COMBINED,
    }

    for col in ['O_B', 'O_L', 'O_joint', 'F_B', 'F_L', 'F_joint']:
        results[f'enacted_{col}'] = enacted_scores[col]
        results[f'mean_{col}']    = spoke_df[col].mean()
        results[f'median_{col}']  = spoke_df[col].median()
        results[f'sd_{col}']      = spoke_df[col].std()
        results[f'p5_{col}']      = spoke_df[col].quantile(0.05)
        results[f'p95_{col}']     = spoke_df[col].quantile(0.95)

    # Ensemble-frontier standardized scores using the canonical O(pi)
    for col in ['O_B', 'O_L', 'O_joint']:
        results[f'Z_{col}'] = _z(enacted_scores[col], col)

    # Primary B-C exact p-values on calibrated F(pi)
    for label, col in [('B', 'F_B'), ('L', 'F_L'), ('joint', 'F_joint')]:
        p_low, p_high, rank = _pval(enacted_scores[col], col)
        results[f'p_{label}_lower'] = p_low
        results[f'p_{label}_upper'] = p_high
        results[f'rank_{label}'] = rank

    # Secondary p-values on canonical O(pi), useful for transparency
    for label, col in [('O_B', 'O_B'), ('O_L', 'O_L'), ('O_joint', 'O_joint')]:
        p_low, p_high, rank = _pval(enacted_scores[col], col)
        results[f'p_{label}_lower'] = p_low
        results[f'p_{label}_upper'] = p_high
        results[f'rank_{label}'] = rank

    return results


