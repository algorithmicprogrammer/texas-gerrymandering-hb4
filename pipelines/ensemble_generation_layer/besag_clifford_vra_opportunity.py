# STEP 2 — Hub chain  (identical to besag_clifford_vra.py)
# ============================================================


def run_hub_chain(enacted_partition):
    """
    Run the chain forward L_HUB steps from the enacted map to reach hub X*.

    Because reversible ReCom is reversible with respect to the spanning-tree
    distribution, running it forward L_HUB steps from the enacted plan is
    distributionally equivalent to running the reverse kernel L_HUB steps.
    That is what lets the enacted plan play the role of one spoke off the hub:
    the hub is L_HUB reverse-steps "behind" the enacted plan, and each spoke is
    L_SPOKE forward-steps "ahead" of the hub. Exactness requires L_HUB ==
    L_SPOKE (both are L_WALK here), so the enacted plan and every spoke are the
    same number of steps from the hub and hence exchangeable under H_0.

    Also prints the realized accepted-move fraction (1 - self-loop rate). This
    is a diagnostic to REPORT, not a knob to tune mid-run: REVRECOM_M and
    L_WALK are fixed in advance, and the accepted-move fraction just tells you
    whether they were generous enough for the spokes to travel.
    """
    print(f"\n=== Running hub chain ({L_HUB} steps) ===")
    t0       = time.time()
    hub_seed = stdlib_random.randint(0, 10**9)
    stdlib_random.seed(hub_seed)

    proposal, chain_constraints = _build_proposal_and_constraint(enacted_partition)
    chain = MarkovChain(
        proposal=proposal,
        constraints=chain_constraints,
        accept=accept.always_accept,
        initial_state=enacted_partition,
        total_steps=L_HUB,
    )
    hub_partition = enacted_partition
    prev_assignment = dict(enacted_partition.assignment)
    accepted_moves = 0
    n_seen = 0
    for step in chain:
        cur_assignment = dict(step.assignment)
        if n_seen > 0 and cur_assignment != prev_assignment:
            accepted_moves += 1
        prev_assignment = cur_assignment
        n_seen += 1
        hub_partition = step

    transitions = max(1, n_seen - 1)
    accept_frac = accepted_moves / transitions
    reverr_rate = (REVERR_COUNT / PROPOSAL_COUNT) if PROPOSAL_COUNT else 0.0
    hub_assignment = dict(hub_partition.assignment)
    hub_elapsed = time.time() - t0
    print(f"  Hub reached in {hub_elapsed:.1f}s.")
    print(f"  Accepted-move fraction: {accept_frac:.3f} "
          f"({accepted_moves} moves / {transitions} steps; "
          f"REVRECOM_M={REVRECOM_M}, L_WALK={L_WALK}).")
    print(f"  Reversibility M-bound hit rate: {reverr_rate:.4f} "
          f"({REVERR_COUNT}/{PROPOSAL_COUNT} proposals self-looped on the "
          f"M-bound).")
    if reverr_rate > 0.001:
        print("  WARNING: reversible ReCom self-looped on the M-bound and/or "
              "an isolated-node (IndexError) failure. M-bound self-loops are "
              "safe but a high rate suggests raising REVRECOM_M. Isolated-node "
              "self-loops are MORE serious: they mean the enacted plan likely "
              "has a discontiguous district, so it sits outside the support of "
              "the spanning-tree target and the exact p-value is ill-posed. "
              "Run diagnose_and_repair_graph.py to check and repair the graph "
              "BEFORE trusting any result.")
    # GeoSim revision: the accepted-move fraction is the quantity that makes
    # "k = L_WALK steps" interpretable -- it converts nominal steps into
    # realized recombination moves, which is what a reader needs in order to
    # judge how local the hub-and-spoke comparison is.
    hub_diagnostics = {
        'hub_seed': hub_seed,
        'hub_elapsed_s': hub_elapsed,
        'hub_steps': L_HUB,
        'hub_accepted_moves': accepted_moves,
        'hub_accept_fraction': accept_frac,
        'revrecom_M_bound_hit_rate': reverr_rate,
        'frac_precincts_moved_enacted_to_hub': (
            sum(1 for n in hub_assignment
                if hub_assignment[n] != ENACTED_ASSIGNMENT[n]) / len(hub_assignment)
            if ENACTED_ASSIGNMENT else float('nan')
        ),
    }
    if accept_frac < 0.02:
        print("  WARNING: very low accepted-move fraction. Spokes may barely "
              "leave the hub, weakening power. Consider raising REVRECOM_M "
              "and/or L_WALK (keep them fixed for the production run) -- this "
              "does not affect validity, only power.")
    return hub_assignment, hub_diagnostics


